document.addEventListener("DOMContentLoaded", () => {
  const bookingReferenceNumber = document.getElementById(
    "bookingReferenceNumber",
  );
  const ownerName = document.getElementById("ownerName");
  const ownerPhone = document.getElementById("ownerPhone");
  const petName = document.getElementById("petName");
  const petType = document.getElementById("petType");
  const petBreed = document.getElementById("petBreed");
  const petSize = document.getElementById("petSize");
  const selectedService = document.getElementById("selectedService");
  const selectedAddOn = document.getElementById("selectedAddOn");
  const specialInstructions = document.getElementById("specialInstructions");
  const estimatedTotalPrice = document.getElementById("estimatedTotalPrice");
  const appointmentDate = document.getElementById("appointmentDate");
  const appointmentTime = document.getElementById("appointmentTime");
  const groomingConsentStatus = document.getElementById(
    "groomingConsentStatus",
  );
  const sedationConsentStatus = document.getElementById(
    "sedationConsentStatus",
  );
  const digitalSignatureValue = document.getElementById(
    "digitalSignatureValue",
  );
  const consentDateValue = document.getElementById("consentDateValue");
  const printConfirmationButton = document.getElementById(
    "printConfirmationButton",
  );
  const confirmationStatus = document.getElementById("confirmationStatus");

  /*
    BACKEND NOTE:
    This page currently reads data from sessionStorage as a temporary front-end placeholder.

    Replace these with:
    - real booking record from backend
    - authenticated user profile data
    - booking reference generated by your server/database
    - pricing returned by backend after service calculation
  */
  const bookingStep1 = getStoredData("bookingStep1");
  const bookingStep2 = getStoredData("bookingStep2");
  const bookingStep3 = getStoredData("bookingStep3");
  const bookingConsentStep = getStoredData("bookingConsentStep");

  populateConfirmationData();

  printConfirmationButton.addEventListener("click", () => {
    window.print();
  });

  function populateConfirmationData() {
    const tempReferenceNumber = generateTemporaryBookingReference();

    /*
      BACKEND NOTE:
      The temporary reference number below should be removed once your backend
      already generates the final official booking reference number after confirmation.
    */
    bookingReferenceNumber.textContent = tempReferenceNumber;

    ownerName.textContent =
      bookingConsentStep?.digitalSignature ||
      bookingStep1?.ownerName ||
      bookingStep2?.ownerName ||
      "No owner name available.";

    ownerPhone.textContent =
      bookingStep1?.ownerPhone ||
      bookingStep2?.ownerPhone ||
      "No contact number available.";

    petName.textContent = bookingStep2?.petName || "No pet selected.";
    petType.textContent =
      formatLabel(bookingStep2?.petType) || "No pet type available.";
    petBreed.textContent = bookingStep2?.petBreed || "Breed not specified.";
    petSize.textContent =
      formatLabel(bookingStep2?.petSize) || "Size not specified.";

    selectedService.textContent =
      formatServiceName(bookingStep3?.servicePackage) || "No service selected.";

    selectedAddOn.textContent = formatAddOns(bookingStep3?.addOns);
    specialInstructions.textContent =
      bookingStep3?.specialInstructions || "No special instructions provided.";

    appointmentDate.textContent =
      bookingStep2?.bookingDate ||
      bookingStep1?.bookingDate ||
      "No booking date selected.";

    appointmentTime.textContent =
      bookingStep2?.bookingTime ||
      bookingStep1?.bookingTime ||
      "No booking time selected.";

    groomingConsentStatus.textContent =
      bookingConsentStep?.groomingAgreementAccepted
        ? "Agreed"
        : "Not confirmed";

    sedationConsentStatus.textContent =
      bookingConsentStep?.sedationConsentAccepted ? "Agreed" : "Not confirmed";

    digitalSignatureValue.textContent =
      bookingConsentStep?.digitalSignature || "No signature available.";

    consentDateValue.textContent =
      bookingConsentStep?.consentDate || "No consent date available.";

    estimatedTotalPrice.textContent = getEstimatedPrice();

    updateConfirmationStatus();
  }

  function getEstimatedPrice() {
    const petTypeValue = (bookingStep2?.petType || "").toLowerCase();
    const petSizeValue = normalizeSize(bookingStep2?.petSize || "");
    const serviceValue = bookingStep3?.servicePackage || "";

    /*
      BACKEND NOTE:
      This is only a temporary front-end estimate table.
      Replace this with real pricing logic from your backend/database.
      Final price should come from:
      - selected service
      - confirmed pet size
      - coat condition
      - add-ons
      - clinic-side adjustments
    */
    const dogPriceTable = {
      partial_grooming: {
        small: 400,
        medium: 500,
        large: 600,
        extra_large: 700,
      },
      regular_dog_grooming: {
        small: 550,
        medium: 650,
        large: 850,
        extra_large: 1050,
      },
      deluxe_dog_grooming: {
        small: 650,
        medium: 750,
        large: 1000,
        extra_large: 1200,
      },
      bath_and_go: {
        small: 450,
        medium: 550,
        large: 650,
        extra_large: 750,
      },
    };

    const catPriceTable = {
      cat_full_grooming: {
        small: 500,
        medium: 600,
      },
    };

    if (petTypeValue === "dog") {
      const servicePrices = dogPriceTable[serviceValue];
      if (servicePrices && servicePrices[petSizeValue]) {
        return `₱${servicePrices[petSizeValue].toLocaleString("en-PH")}`;
      }

      if (serviceValue === "partial_grooming") return "₱400 - ₱700+";
      if (serviceValue === "regular_dog_grooming") return "₱550 - ₱1,050+";
      if (serviceValue === "deluxe_dog_grooming") return "₱650 - ₱1,200+";
      if (serviceValue === "bath_and_go") return "₱450 - ₱750+";
    }

    if (petTypeValue === "cat") {
      const servicePrices = catPriceTable[serviceValue];
      if (servicePrices && servicePrices[petSizeValue]) {
        return `₱${servicePrices[petSizeValue].toLocaleString("en-PH")}`;
      }

      if (serviceValue === "cat_full_grooming") return "₱500 - ₱600";
      if (serviceValue === "cat_alacarte")
        return "Varies by selected cat service";
    }

    return "To be confirmed by clinic.";
  }

  function formatAddOns(addOns) {
    if (!Array.isArray(addOns) || addOns.length === 0) {
      return "No add-on selected.";
    }

    return addOns
      .map((item) => item.replaceAll("_", " "))
      .map((item) => item.replace(/\b\w/g, (char) => char.toUpperCase()))
      .join(", ");
  }

  function formatServiceName(value) {
    if (!value) return "";
    return value
      .replaceAll("_", " ")
      .replace(/\b\w/g, (char) => char.toUpperCase());
  }

  function formatLabel(value) {
    if (!value) return "";
    return String(value)
      .replaceAll("_", " ")
      .replace(/\b\w/g, (char) => char.toUpperCase());
  }

  function normalizeSize(size) {
    const normalized = String(size).toLowerCase().trim();

    if (normalized === "small") return "small";
    if (normalized === "medium") return "medium";
    if (normalized === "large") return "large";
    if (
      normalized === "extra large" ||
      normalized === "extra_large" ||
      normalized === "xl"
    ) {
      return "extra_large";
    }

    return normalized;
  }

  function generateTemporaryBookingReference() {
    const characters = "ABCDEFGHJKLMNPQRSTUVWXYZ0123456789";
    let suffix = "";

    for (let i = 0; i < 4; i += 1) {
      suffix += characters.charAt(
        Math.floor(Math.random() * characters.length),
      );
    }

    return `GRM-${suffix}`;
  }

  function updateConfirmationStatus() {
    const hasConsent =
      bookingConsentStep?.groomingAgreementAccepted &&
      bookingConsentStep?.sedationConsentAccepted &&
      bookingConsentStep?.digitalSignature;

    if (hasConsent) {
      confirmationStatus.textContent =
        "Booking confirmation is complete. This page is currently using temporary front-end generated values where backend data is not yet connected.";
      confirmationStatus.className =
        "mb-6 rounded-2xl border border-green-300 bg-green-50 px-4 py-3 text-sm text-green-700";
      return;
    }

    confirmationStatus.textContent =
      "Some confirmation details are missing or still using empty-state placeholders. Backend integration will complete the final values.";
    confirmationStatus.className =
      "mb-6 rounded-2xl border border-[#9bb9d3] bg-white px-4 py-3 text-sm text-slate-600";
  }

  function getStoredData(key) {
    try {
      const rawValue = sessionStorage.getItem(key);
      return rawValue ? JSON.parse(rawValue) : null;
    } catch (error) {
      console.error(`Failed to parse sessionStorage key: ${key}`, error);
      return null;
    }
  }
});
